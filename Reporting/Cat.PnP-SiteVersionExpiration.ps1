$pauseDuration = 120
$specialCharacters = "[#@$%*&()/\| ():<>?]"
# $reportLibraryTemplate = "DocumentLibrary"

# User Input Variables
Write-Host
Write-Host "User Input Variables" -ForegroundColor Cyan
$certPass = ConvertTo-SecureString -String (Read-Host -Prompt "   Enter certificate password for the app registration") -AsPlainText -Force
$cert = Get-PnPAzureCertificate -Path $clientCertPath -Password $certPass
Remove-Variable certPass
Remove-Variable clientCertPath
Write-Host ("   Sign in with the Site Admin Account: {0}" -f $siteAdminUPN)
$interactiveConnection = Connect-PnPOnline -Url $tenantSPOURL -Interactive -ClientId $clientInteractiveAppID -ValidateConnection -ReturnConnection -ErrorAction Stop # Interactive Login requires PNP Interactive App Reg be deployed by a GA. 

#region Output Parameters & Variables
Write-Host
Write-Host "Script Parameters" -ForegroundColor Cyan
Write-Host ("   Input File: {0}" -f $inputFile)
Write-Host ("   App ID: {0}" -f $clientAppID)
Write-Host ("   Client Tenant Prefix: {0}" -f $clientTenant)
Write-Host ("   Report Library Path: {0}" -f $reportLibraryPath)
<#Write-Host # Uncomment if Troubleshooting only
