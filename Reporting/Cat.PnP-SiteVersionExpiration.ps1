Write-Host ("   Special Characters: {0}" -f $specialCharacters)
#endregion Output Parameters & Variables
#endregion
    
#region 4.	Main Script
#region Created directories for reports
Write-Host
Write-Host ("{0} - Creating Report Directories" -f (Get-Date -Format "yy-MM-dd HH:mm:ss")) -ForegroundColor Cyan
$tempFolder = New-Item -Path $outputPath -ItemType Directory
#endregion Created directories for reports

#region Sites CSV Loop
Write-Host
Write-Host ("Looping through sites in CSV File: {0}" -f $inputFile) -ForegroundColor Cyan
:sitesLoop foreach ($site in $inFile){
	Write-Host
	Write-Host ("   {0} - Creating Versioning Report - {1} - {2}" -f (Get-Date -Format "yy-MM-dd HH:mm:ss"), $site.Title, $site.Url) -ForegroundColor Magenta

	#region Connecting to SharePoint with App Reg
	Write-Host ("      {0} - Connecting to SharePoint Site with App Reg: {1}" -f (Get-Date -Format "yy-MM-dd HH:mm:ss"), $site.Url)
	Connect-PnPOnline $site.Url -tenant $tenantDomain -ClientId $clientAppID -Thumbprint $cert.Thumbprint -ValidateConnection -ErrorAction Stop # PnP Modules w/ App Reg
	#endregion Connecting to SharePoint with App Reg

	#region Adding Site Collection Administrator
	Write-Host ("         {0} - Adding site collection administrator: {1}" -f (Get-Date -Format "yy-MM-dd HH:mm:ss"), $siteAdminUPN) -ForegroundColor DarkGray
	Add-PnPSiteCollectionAdmin -Owners $siteAdminUPN -ErrorAction Stop
	#endregion

	#region Creating Reports Library
	Write-Host ("         {0} - Creating Report Library: {1}" -f (Get-Date -Format "yy-MM-dd HH:mm:ss"), $reportLibraryPath) -NoNewline -ForegroundColor DarkGray
	$library = Get-PnPList -Identity $reportLibraryPath -ErrorAction SilentlyContinue
	if ($library) {
		Write-Host (" - Already Exists") -ForegroundColor DarkGray
	}
	else {          
		try {
			$tempLibrary = New-PnPList -Title $reportLibraryPath -Template DocumentLibrary -OnQuickLaunch:$false
			Write-Host (" - Created") -ForegroundColor DarkGray
		}
		catch {
			# Output Error Information
			Write-CatErrorCSV -funcCSVItem $job -funcAction "Creating Library" -funcException $_.Exception -funcDetails $_.ErrorDetails -funcStackTrace $_.ScriptStackTrace -funcFilePath $errorPath
		}
	}
	#endregion

	#region Disconnecting from App Reg Auth
	Write-Host ("         {0} - Disconnecting from App Reg Auth" -f (Get-Date -Format "yy-MM-dd HH:mm:ss")) -ForegroundColor DarkGray
	Disconnect-PnPOnline
	#endregion

	#region Connecting to SharePoint with Interactive
	Write-Host ("      {0} - Connecting to SharePoint Site with Interactive: {1}" -f (Get-Date -Format "yy-MM-dd HH:mm:ss"), $site.Url)
	Connect-PnPOnline -Url $site.Url -Interactive -ClientId $clientInteractiveAppID -Connection $interactiveConnection -ValidateConnection -ErrorAction Stop # Interactive Login requires PNP Interactive App Reg be deployed by a GA. 

	#endregion Connecting to SharePoint with Interactive
	
	#region New Report Job
	$reportUrl = ("{0}/{1}/{2}-SiteVersionExpirationReport-{3}.csv" -f $site.Url, $reportLibraryPath, ($site.Title -replace $specialCharacters), (Get-Date -Format "yyMMddHHmmss"))
	Write-Host ("         {0} - Report URL: [SiteUrl]{1}" -f (Get-Date -Format "yy-MM-dd HH:mm:ss"), $reportUrl.Replace($site.Url,"")) -ForegroundColor DarkGray
	$jobTemp = New-PnPSiteFileVersionExpirationReportJob -ReportUrl $reportUrl
	#endregion

	<# Job info Output for Troubleshooting
	Write-Host
	$jobTemp | Format-List *
	Write-Host #>
	#endregion

	#region Checking Report Status
	Write-Host ("         {0} - Waiting for Report completion (Checks every {1} minutes)" -f (Get-Date -Format "yy-MM-dd HH:mm:ss"), ($pauseDuration/60)) -NoNewline -ForegroundColor DarkGray
	$reportStatus = Get-PnPSiteFileVersionExpirationReportJobStatus -ReportUrl $reportUrl
	while ($reportStatus.Status -eq "in_progress") {
		Start-Sleep -Seconds $pauseDuration
		Write-Host "." -NoNewline -ForegroundColor DarkGray
		$reportStatus = Get-PnPSiteFileVersionExpirationReportJobStatus -ReportUrl $reportUrl
	}
	Write-Host "." -ForegroundColor DarkGray
	#endregion

	#region Downloading Report
	Write-Host ("         {0} - Downloading Report File" -f (Get-Date -Format "yy-MM-dd HH:mm:ss")) -ForegroundColor DarkGray
	Get-PnPFile -Url $reportUrl -Path $outputPath -Filename ([System.IO.Path]::GetFileName($reportUrl)) -AsFile #-Force
	#endregion

	#region Reporting Job Status
	Write-Host ("         {0} - Report Completion Status: " -f (Get-Date -Format "yy-MM-dd HH:mm:ss")) -NoNewline -ForegroundColor DarkGray
	switch ($reportStatus.Status) {
		failed {Write-Host ("{0}" -f $reportStatus.Status) -ForegroundColor Red}
		completed {Write-Host ("{0}" -f $reportStatus.Status) -ForegroundColor Green}
		Default {Write-Host ("{0}" -f $reportStatus.Status) -ForegroundColor Yellow}
	}
	Write-Host ("         {0} - Disconnecting from Interactive Auth" -f (Get-Date -Format "yy-MM-dd HH:mm:ss")) -ForegroundColor DarkGray

	<# Status Output for Troubleshooting
	Write-Host
	$reportStatus | Format-List *
	$reportStatus | ConvertTo-Json -Depth 20
	Write-Host #>
	#endregion

	#region Connecting to SharePoint with App Reg
	Write-Host ("      {0} - Connecting to SharePoint Site with App Reg: {1}" -f (Get-Date -Format "yy-MM-dd HH:mm:ss"), $site.Url)
	Connect-PnPOnline $site.Url -tenant $tenantDomain -ClientId $clientAppID -Thumbprint $cert.Thumbprint -ValidateConnection -ErrorAction Stop # PnP Modules w/ App Reg
	#endregion Connecting to SharePoint with App Reg

	#region Removing Site Collection Administrator
	Write-Host ("         {0} - Removing site collection administrator: {1}" -f (Get-Date -Format "yy-MM-dd HH:mm:ss"), $siteAdminUPN) -ForegroundColor DarkGray
	Remove-PnPSiteCollectionAdmin -Owners $siteAdminUPN -Connection $srcSiteConnection
	#endregion

	#region Disconnecting from App Reg Auth
	Write-Host ("         {0} - Disconnecting from App Reg Auth" -f (Get-Date -Format "yy-MM-dd HH:mm:ss")) -ForegroundColor DarkGray
	Disconnect-PnPOnline
	#endregion

	<#region Sub Task / Error Handling Example
	Write-Host "      Doing Sub action" -ForegroundColor DarkGray
	try {
		$group = Get-PnPMicrosoft365Group -Identity $site.GroupId -ErrorAction Stop
	}
	catch {
		Write-CatErrorCSV -funcCSVItem $site -funcAction "Doing Sub action" -funcException $_.Exception -funcDetails $_.ErrorDetails -funcStackTrace $_.ScriptStackTrace -funcFilePath $errorPath
		Continue sitesLoop
	}
	#endregion Sub Task / Error Handling Example #>
} 
#endregion Sites CSV Loop
#endregion Main Script

#region Completed Script
# Output Script Info
Complete-CatScript $scriptStart[0]

# Stop logging
Stop-Transcript
#endregion Completed Script