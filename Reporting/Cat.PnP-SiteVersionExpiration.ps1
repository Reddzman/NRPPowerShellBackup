<# Overview 
.SYNOPSIS
Cat.PnP-SiteVersionExpiration.ps1

.DESCRIPTION
Generates SharePoint Online Site File Version Expiration Reports for one or more
sites defined in a CSV input file.

The script leverages PnP PowerShell authentication using both App Registration
(App-Only) and Interactive authentication methods to perform the following actions:

    • Connect to each SharePoint Online site specified in the CSV file
    • Temporarily add a Site Collection Administrator account
    • Create a report library if it does not already exist
    • Submit a Site File Version Expiration Report job
    • Monitor report generation status
    • Download completed report files locally
    • Remove the temporary Site Collection Administrator
    • Log errors and transcript output for troubleshooting

Reports generated by Microsoft contain information about file versions eligible
for expiration based on SharePoint version history policies. This can be useful
for storage optimization, governance reviews, and version cleanup planning.

.DEPENDENCIES
    PowerShell Modules
        - PnP.PowerShell
        - Cat.GeneralFunctions.psm1

    Required Functions
        - Start-CatScript
        - Complete-CatScript
        - Write-CatErrorCSV

    Input File
        - CSV file containing SharePoint site information
        - Example:
            ..\_Input Files\Cat.SiteVersionExpiration.csv

.INPUTS
CSV containing site information.

Expected columns:
    - Title
    - Url

Example:

    Title,Url
    Human Resources,https://contoso.sharepoint.com/sites/HR
    Finance,https://contoso.sharepoint.com/sites/Finance

.OUTPUTS
Creates the following output:

    - Site Version Expiration Report CSV files
    - Error CSV file (if applicable)
    - PowerShell Transcript Log

Output Folder Structure:

    <OutputLocation>\<Tenant>\<DateTime>\

Example:

    C:\GitHub\CatPowerShell\_Output Files\Contoso\260811-093000\HR-SiteVersionExpirationReport-260811093015.csv

.AUTHENTICATION

    App Registration Authentication
        - Used for site administration tasks
        - Requires:
            • Client ID
            • Certificate
            • Certificate Password

    Interactive Authentication
        - Used for report generation commands
        - Requires:
            • Interactive PnP App Registration
            • User sign-in

.PARAMETERS

    -inputFile
        Path to the input CSV relative to the _Input Files folder.

    -clientAppID
        Azure AD App Registration Client ID used for App-Only authentication.

    -clientCertPath
        Path to the PFX certificate used by the App Registration.

    -clientInteractiveAppID
        App Registration Client ID used for Interactive PnP authentication.

    -clientTenant
        Tenant SharePoint prefix.
        Example: contoso

    -siteAdminUPN
        User Principal Name used as temporary Site Collection Administrator.

    -outputLocation
        Root output location for reports and logs.

    -reportLibraryPath
        Document library used to store report files within each site.

