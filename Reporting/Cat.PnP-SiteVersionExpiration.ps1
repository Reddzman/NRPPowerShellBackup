.PROCESS OVERVIEW

    1. Load required modules and functions
    2. Validate input CSV
    3. Prompt for certificate password
    4. Establish interactive tenant connection
    5. Loop through sites in CSV
    6. Connect using App Registration
    7. Add Site Collection Administrator
    8. Create report library if required
    9. Generate Version Expiration Report
    10. Monitor report status
    11. Download report locally
    12. Remove Site Collection Administrator
    13. Disconnect sessions
    14. Write transcript and completion details

#>

